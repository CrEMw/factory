#!/bin/sh
# Step 2.12b of the factory plan: the migration chain and the baseline schema give the same catalog. Only on a machine
# with docker (the pg-schema part of tools/check.sh runs it when docker is there; the gate has no docker and checks
# only that the canonical migrations reproduce the baseline texts, tools/canonical-bodies.sh --check).
#   sh tools/test-pg-schema.sh              compare; on a difference print it and exit 1
#   sh tools/test-pg-schema.sh --expected   compare, then print SQL with the md5 of the baseline catalog and of each
#                                           of its lines (input of the clone rehearsal: deploy/restore-check)
#   sh tools/test-pg-schema.sh --write-catalog
#                                           compare, then write the baseline catalog to services/hub/baseline/catalog.txt
# The expected catalog services/hub/baseline/catalog.txt (step 2.12c, embedded in `hub migrate --adopt`, see
# docs/migrations.md) must equal the catalog of the baseline: without --write-catalog a difference is an error.
# Starts a temporary postgres:18.7 container (the digest of tools/test-graph-pg.sh), applies services/hub/migrations
# in order to database chain and services/hub/baseline/1000_baseline.sql to database base, each file in its own
# transaction with its sqlx journal row, and compares the lines of services/hub/pg-schema.sql byte for byte. The container
# is removed on any exit.
set -eu
cd "$(dirname "$0")/.."
mode="${1:-}"
case "$mode" in ""|--expected|--write-catalog) ;; *) echo "usage: sh tools/test-pg-schema.sh [--expected|--write-catalog]" >&2; exit 2 ;; esac
catalog=services/hub/baseline/catalog.txt
name="hub-pg-schema-$$"
image="$(sed -n 's/^image=//p' tools/test-graph-pg.sh)"
[ -n "$image" ] || { echo "no image= line in tools/test-graph-pg.sh" >&2; exit 2; }
out="$(mktemp -d)"
trap 'docker rm -f "$name" >/dev/null 2>&1 || true; rm -rf "$out"' EXIT INT TERM
docker run -d --rm --name "$name" -e POSTGRES_PASSWORD=x -e POSTGRES_DB=chain "$image" >/dev/null
psql_() { docker exec -i "$name" psql -X -q -v ON_ERROR_STOP=1 -U postgres "$@"; }
i=0
until psql_ -d chain -c 'select 1' >/dev/null 2>&1; do
  i=$((i + 1))
  [ "$i" -lt 60 ] || { echo "postgres did not start" >&2; exit 1; }
  sleep 1
done
psql_ -d chain -c 'CREATE DATABASE base' >/dev/null
# Like sqlx: the journal table exists before the first migration, and each migration and its journal row (an
# unqualified INSERT) share one transaction, so a migration that leaves a changed search path breaks here as it would
# in hub migrate.
apply() { # database file version
  { echo 'BEGIN;'; cat "$2"; echo "
INSERT INTO _sqlx_migrations (version, description, success, checksum, execution_time) VALUES ($3, 'test', true, '\\x00', 0);
COMMIT;"; } | psql_ -d "$1" >/dev/null 2>"$out/err" || { cat "$out/err" >&2; echo "FAIL: $2" >&2; exit 1; }
}
for db in chain base; do
  psql_ -d "$db" -c 'CREATE TABLE _sqlx_migrations (version bigint PRIMARY KEY, description text NOT NULL,
    installed_on timestamptz NOT NULL DEFAULT now(), success boolean NOT NULL, checksum bytea NOT NULL, execution_time bigint NOT NULL)' >/dev/null
done
for f in services/hub/migrations/*.sql; do
  v="$(basename "$f" | sed 's/_.*//; s/^0*//')"
  apply chain "$f" "$v"
done
apply base services/hub/baseline/1000_baseline.sql 1000
for db in chain base; do
  { cat services/hub/pg-schema.sql; echo 'SELECT line FROM pg_temp.schema_catalog() AS line ORDER BY line COLLATE "C";'; } | psql_ -d "$db" -t -A >"$out/$db.txt"
done
n="$(wc -l <"$out/base.txt")"
[ "$n" -gt 1000 ] || { echo "FAIL: only $n catalog lines: services/hub/pg-schema.sql no longer sees the schema" >&2; exit 1; }
if ! cmp -s "$out/chain.txt" "$out/base.txt"; then
  diff -u "$out/chain.txt" "$out/base.txt" | cut -c1-400 >&2 || true
  echo "FAIL: the catalog of the chain (-) differs from the baseline (+): change services/hub/baseline/1000_baseline.sql with the migration; sh tools/canonical-bodies.sh prints the function, view and comment texts the migration must carry" >&2
  exit 1
fi
if [ "$mode" = --write-catalog ]; then
  cp "$out/base.txt" "$catalog"
  echo "wrote $catalog ($n lines)"
elif ! cmp -s "$catalog" "$out/base.txt"; then
  diff -u "$catalog" "$out/base.txt" | cut -c1-400 >&2 || true
  echo "FAIL: $catalog (-) is not the catalog of the baseline (+): sh tools/test-pg-schema.sh --write-catalog" >&2
  exit 1
fi
sum="$({ cat services/hub/pg-schema.sql; echo "SELECT md5(string_agg(line, E'\\n' ORDER BY line COLLATE \"C\")) FROM pg_temp.schema_catalog() AS line;"; } | psql_ -d base -t -A)"
ok="ok: chain and baseline give the same catalog ($n lines, md5 $sum)"
[ "$mode" = --expected ] || { echo "$ok"; exit 0; }
echo "$ok" >&2
# The expected catalog of the baseline for a database where the same query runs: the md5 of all lines and of each line.
{
  echo "-- Generated by sh tools/test-pg-schema.sh --expected: the catalog of services/hub/baseline/1000_baseline.sql"
  echo "-- (services/hub/pg-schema.sql, $n lines). Do not edit."
  echo "CREATE TEMP TABLE pg_schema_expected (line_md5 text PRIMARY KEY) ON COMMIT DROP;"
  echo "\\set pg_schema_md5 '$sum'"
  { cat services/hub/pg-schema.sql; echo "SELECT 'INSERT INTO pg_schema_expected VALUES' || string_agg(E'\\n    (' || quote_literal(m) || ')', ',' ORDER BY m COLLATE \"C\") || ';'
      FROM (SELECT DISTINCT md5(line) AS m FROM pg_temp.schema_catalog() AS line) x;"; } | psql_ -d base -t -A
}
